#!/bin/sh
# 自举门禁：用 coCN 自己写的编译器（词法/语法/ELF/机器码，全部是 .co）
# 把 .co 程序编成机器码，并与解释器输出逐字节比对。
#
# 旧版这里还引用根目录的 自举编译器.co / 自举示例.co，两个文件早已合并进
# 工具/自举编译器/，门禁因此长期跑不起来（make bootstrap 直接失败）。
# 现在统一走 工具/自举编译器/自举验证/编译验证.sh：
#   - 拼接 词法分析器.co + 语法分析器.co + elf.co + 机器码生成器.co
#   - 由当前运行时执行这台「coCN 写的编译器」
#   - 10 个真实程序的产物 ELF 与解释器输出逐字节一致
#
# 还没做到的一步：把这台编译器自身编成原生 ELF（stage2）。
# 它用到字典、尝试/捕捉、匿名函数，而 x86-64 原生后端目前不支持这三类写法，
# 所以它暂时只能跑在 coCN 运行时之上。补齐这三项后即可自我编译。
set -e
cd "$(dirname "$0")/.."
exec bash 工具/自举编译器/自举验证/编译验证.sh
