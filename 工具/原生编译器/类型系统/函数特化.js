// ============================================================
// 函数特化.js —— 类型特化引擎：把多态动态函数拆成静态特化版本
//
// 核心思想（JIT/宏分化 风格的 AOT 实现）：
//   原函数 加(a, b) 在不同调用点接收不同类型：
//       加(1, 2)        -> 实参 整数,整数
//       加(1.5, 2.5)    -> 实参 浮点,浮点
//       加("a","b")     -> 实参 字符串,字符串
//   本引擎为【每种实参类型组合】生成一份特化拷贝：
//       加_整数_整数(a,b)    // 内部全是原生 int 运算，零类型检查
//       加_浮点_浮点(a,b)    // 内部全是原生 double 运算
//       加_字符串_字符串(a,b) // 内部是字符串拼接
//   并把每个调用点改写为直连对应特化版本。
//
// 特化版本内：
//   - 形参已绑定具体静态类型（标注在节点上）；
//   - 所有中间表达式的类型在生成时用【特化后】的环境重推一遍，
//     保证下游代码生成器看到的全是确定性原生类型；
//   - 运行时不再需要任何类型 tag 检查 / 分支。
// ============================================================

'use strict';

const T = require('./类型');
const AU = require('./AST工具');
const 类型推断 = require('./类型推断');

class 函数特化 {
  /**
   * @param {object} ast 程序节点
   * @param {object} 推断结果 类型推断.分析() 的输出
   */
  constructor(ast, 推断结果) {
    this.ast = ast;
    this.推断 = 推断结果;
    /** 原始函数表：名字 -> 函数节点 */
    this.原函数 = AU.收集顶层函数(ast);
    /** 生成的特化函数：特化名 -> 函数节点 */
    this.特化函数表 = {};
    /** 调用点改写记录：原调用节点 -> 特化名 */
    this.调用映射 = [];
  }

  // ---------- 入口 ----------
  特化() {
    // 1) 按函数名分组收集调用点（每个调用点带实参具体类型）
    const 按函数 = new Map();   // 函数名 -> [{调用节点, 实参类型}]
    for (const cs of this.推断.调用点) {
      if (!按函数.has(cs.函数名)) 按函数.set(cs.函数名, []);
      按函数.get(cs.函数名).push(cs);
    }

    // 2) 对每个有调用点的函数，按「实参类型组合」特化
    for (const [函数名, 调用列表] of 按函数) {
      const 原节点 = this.原函数[函数名];
      if (!原节点) continue;                       // 内建/外部函数，无法特化
      // 按实参类型元组分组
      const 组 = new Map();
      for (const cs of 调用列表) {
        const key = cs.实参类型.map(T.keyOf).join('|');
        if (!组.has(key)) 组.set(key, { 实参类型: cs.实参类型, 调用点: [] });
        组.get(key).调用点.push(cs.调用节点);
      }
      // 每组生成一个特化版本
      for (const { 实参类型, 调用点 } of 组.values()) {
        const 特化名 = this.生成特化版本(原节点, 函数名, 实参类型);
        for (const callNode of 调用点) {
          callNode.被调者 = { 类型: '标识符', 名字: 特化名, _特化目标: 特化名 };
          this.调用映射.push({ 原调用: callNode, 特化名 });
        }
      }
    }

    // 3) 把所有特化函数追加进程序语句（顶层）
    this.写入程序();
    return {
      ast: this.ast,
      特化函数表: this.特化函数表,
      调用映射: this.调用映射
    };
  }

  // 生成特化函数：深拷贝原函数体，绑定具体形参类型
  生成特化版本(原节点, 函数名, 实参类型) {
    const 后缀 = 实参类型.map(T.shortName).join('_');
    const 特化名 = 函数名 + '__特化_' + 后缀;

    // 单态（只有一种类型组合）时也走同一命名，便于直连
    const 拷贝 = AU.克隆(原节点);
    拷贝.名字 = 特化名;
    拷贝.是否特化 = true;
    拷贝.特化自 = 函数名;
    拷贝.特化参数类型 = 实参类型;

    // 形参节点上标注具体类型
    (拷贝.参数 || []).forEach((p, i) => {
      拷贝['_形参_' + p] = 实参类型[i] || T.bot();
    });

    // 用具体形参类型【重推一遍】函数体，让体内所有表达式拿到精确原生类型。
    // 这一步是「消除类型检查」的关键：原本靠动态 tag 分发的运算，
    // 现在全部退化为静态类型运算。
    this.重推函数体(拷贝, 实参类型);

    this.特化函数表[特化名] = 拷贝;
    return 特化名;
  }

  // 重新推断特化函数体：形参已知为具体类型，跑一遍数据流
  重推函数体(特化节点, 实参类型) {
    // 构造一个仅含该特化函数的迷你程序，复用类型推断的定点引擎
    const 迷你程序 = { 类型: '程序', 语句: [特化节点] };
    const 推断 = new 类型推断(迷你程序);
    // 预置形参类型（避免从 bot 重新爬升，直接给定）
    (特化节点.参数 || []).forEach((p, i) => {
      推断.签名[特化节点.名字] = T.tFunc(特化节点.名字, 实参类型, T.bot());
    });
    推断.分析();
    // 把精确返回类型记到特化节点上
    特化节点._返回类型 = 推断.返回类型[特化节点.名字] || T.bot();
  }

  // 把特化函数写回程序顶层语句
  写入程序() {
    if (!this.ast || !Array.isArray(this.ast.语句)) return;
    for (const 名字 of Object.keys(this.特化函数表)) {
      this.ast.语句.push(this.特化函数表[名字]);
    }
  }
}

// ============================================================
// 数据结构特化：把装箱容器类型提升为紧凑原生布局
//
//   列表<整数>      -> int[]   （连续内存，无 tag）
//   列表<浮点>      -> double[]
//   列表<字符串>    -> char*[]
//   列表<混合>      -> boxed[]（保留装箱）
//   字典<字符串,值> -> 字符串键哈希表（更紧凑）
//
// 本模块遍历已标注类型的 AST，把 list/dict 类型的 specialized 位置位，
// 并在节点上记录「布局决策」供代码生成器直接分配原生数组。
// ============================================================
function 特化数据结构(ast, 推断结果) {
  const 布局决策 = [];
  AU.遍历(ast, (node) => {
    const t = node._类型;
    if (!t) return;
    if (t.k === 'list') {
      // 元素类型单一 -> 紧凑布局
      let layout = 'boxed[]';
      if (t.elem.k === 'int') layout = 'int[]';
      else if (t.elem.k === 'float') layout = 'double[]';
      else if (t.elem.k === 'str') layout = 'str[]';
      t.layout = layout;
      t.specialized = (layout !== 'boxed[]');
      if (node.类型 === '列表字面量' || node.类型 === '变量声明') {
        布局决策.push({ 节点: node, 类型: t, 布局: layout });
      }
    } else if (t.k === 'dict') {
      t.specialized = (t.key.k === 'str');   // 字符串键可用紧凑哈希
    }
  });
  return { 布局决策 };
}

module.exports = 函数特化;
module.exports.特化数据结构 = 特化数据结构;
