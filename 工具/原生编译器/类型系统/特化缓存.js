// ============================================================
// 特化缓存.js —— 运行时类型反馈缓存（JIT 风格，AOT 下也可用）
//
// AOT 编译时，我们靠【静态分析】推断类型、生成特化版本。但静态分析
// 不可能 100% 准确——遇到「类型漂移」「跨模块」「动态分发」时只能
// 退回动态。此时本模块提供一个【一层内联缓存（1-level inline cache）】：
//
//   - 在每个尚无法静态特化的调用点，嵌入一个缓存槽：
//       struct 调用点缓存 { 函数* 上次目标; 类型签名 上次类型; };
//   - 首次执行：检查实参类型，命中则记下目标；
//   - 后续执行：实参类型与上次一致 -> 直接调用缓存目标，零类型分发；
//   - 类型变化：去优化（deopt）回通用路径，并在「热路径」触发重新特化。
//
// AOT 阶段本文件只负责【标记调用点、生成缓存槽描述】，真正的运行时
// 逻辑由代码生成器 / 运行时.c 实现。
// ============================================================

'use strict';

const AU = require('./AST工具');

class 特化缓存 {
  /**
   * @param {object} ast 程序节点
   * @param {object} 推断结果 类型推断结果
   */
  constructor(ast, 推断结果) {
    this.ast = ast;
    this.推断 = 推断结果;
    /** 缓存槽描述：[{调用节点, 函数名, 实参类型}] */
    this.缓存槽 = [];
  }

  // 扫描所有「未能静态特化」的调用点，登记为运行时缓存点
  登记() {
    let id = 0;
    AU.遍历(this.ast, (node) => {
      if (node.类型 !== '函数调用') return;
      // 已静态特化的调用点不进缓存（直连即可）
      if (node._特化目标) return;
      // 已标内联缓存的也登记
      if (node.被调者 && node.被调者.类型 === '标识符') {
        const 函数名 = node.被调者.名字;
        node._缓存槽号 = id;
        node._可去优化 = true;
        this.缓存槽.push({
          槽号: id,
          调用节点: node,
          函数名,
          实参类型: (node.参数 || []).map(a => a._类型 || null)
        });
        id++;
      }
    });
    return this.缓存槽;
  }

  /**
   * 模拟运行时反馈：给定一个调用点观测到的实际类型签名，
   * 若与缓存记录不同则标记「需重新特化」（供 JIT 重编译用）。
   * AOT 下默认关闭；这里提供接口，便于未来接入 JIT。
   */
  记录反馈(槽号, 实际类型) {
    const 槽 = this.缓存槽[槽号];
    if (!槽) return false;
    const 变化 = !sameTypes(槽.实参类型, 实际类型);
    if (变化) {
      槽.上次实际类型 = 实际类型;
      槽.需重新特化 = true;
    }
    return 变化;
  }
}

function sameTypes(a, b) {
  if (!a || !b || a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) {
    if ((a[i] && a[i].k) !== (b[i] && b[i].k)) return false;
  }
  return true;
}

module.exports = 特化缓存;
