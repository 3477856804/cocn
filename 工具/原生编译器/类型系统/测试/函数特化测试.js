// 函数特化测试.js —— 验证多态函数生成多个特化版本
// ============================================================
'use strict';

const 类型推断 = require('../类型推断');
const 函数特化 = require('../函数特化');
const T = require('../类型');

const 整 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '整数' });
const 点 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '浮点' });
const 串 = v => ({ 类型: '字面量', 值: v, 字面类型: '字符串' });
const 标 = n => ({ 类型: '标识符', 名字: n });
const 加 = (l, r) => ({ 类型: '二元', 运算符: '+', 左: l, 右: r });
const 调 = (n, args) => ({ 类型: '函数调用', 被调者: 标(n), 参数: args });
const 声明 = (n, init) => ({ 类型: '变量声明', 名字: n, 初始化: init });
const 返回 = v => ({ 类型: '返回', 值: v });
const 函数 = (n, ps, body) => ({
  类型: '函数定义', 名字: n, 参数: ps, 参数类型: [], 参数默认: [],
  返回类型: '', 体: { 类型: '程序', 语句: body }
});

module.exports.运行 = ({ 断言, 等于, 组名 }) => {
  组名('函数特化：多态函数拆分为多个特化版本');

  const ast = { 类型: '程序', 语句: [
    函数('加', ['a', 'b'], [ 返回(加(标('a'), 标('b'))) ]),
    声明('r1', 调('加', [整(1), 整(2)])),
    声明('r2', 调('加', [点(1.5), 点(2.5)])),
    声明('r3', 调('加', [串('a'), 串('b')]))
  ]};
  const 推断结果 = new 类型推断(ast).分析();
  const sp = new 函数特化(ast, 推断结果);
  const out = sp.特化();

  const 名集 = Object.keys(out.特化函数表);
  断言(名集.length >= 3, `应为每个类型组合生成特化版本（实际 ${名集.length} 个）`);
  断言(名集.some(n => n.indexOf('整数_整数') >= 0), '存在 加_整数_整数 特化版');
  断言(名集.some(n => n.indexOf('浮点_浮点') >= 0), '存在 加_浮点_浮点 特化版');
  断言(名集.some(n => n.indexOf('字符串_字符串') >= 0), '存在 加_字符串_字符串 特化版');

  组名('函数特化：特化版本内类型确定（零运行时检查）');

  // 整数特化版的返回类型应为 int
  const 整数版 = out.特化函数表[名集.find(n => n.indexOf('整数_整数') >= 0)];
  等于(T.keyOf(整数版._返回类型), 'int', '加_整数_整数 返回 int');
  const 浮点版 = out.特化函数表[名集.find(n => n.indexOf('浮点_浮点') >= 0)];
  等于(T.keyOf(浮点版._返回类型), 'float', '加_浮点_浮点 返回 float');

  组名('函数特化：调用点改写为直连特化版本');

  等于(out.调用映射.length, 3, '三个调用点都被改写');
  for (const m of out.调用映射) {
    断言(m.原调用.被调者.名字.indexOf('加__特化_') === 0,
      '调用点被改写为特化函数名');
  }

  组名('数据结构特化：列表布局');

  const ast2 = { 类型: '程序', 语句: [
    声明('nums', { 类型: '列表字面量', 元素: [整(1), 整(2), 整(3)], 是否推导式: 0 })
  ]};
  const ti2 = new 类型推断(ast2).分析();
  函数特化.特化数据结构(ast2, ti2);
  const numsDecl = ast2.语句[0];
  等于(numsDecl._类型.layout, 'int[]', '整数列表特化为 int[] 连续布局');
};
