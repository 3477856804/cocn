// ============================================================
// 逃逸分析测试.js —— 验证不逃逸对象被标量替换
// ============================================================
'use strict';

const TS = require('../index');
const T = TS.类型;

const 整 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '整数' });
const 标 = n => ({ 类型: '标识符', 名字: n });
const 调 = (n, args) => ({ 类型: '函数调用', 被调者: 标(n), 参数: args });
const 声明 = (n, init) => ({ 类型: '变量声明', 名字: n, 初始化: init });
const 下标 = (c, i) => ({ 类型: '下标', 容器: c, 索引: i });
const 返回 = v => ({ 类型: '返回', 值: v });
const 函数 = (n, ps, body) => ({
  类型: '函数定义', 名字: n, 参数: ps, 参数类型: [], 参数默认: [],
  返回类型: '', 体: { 类型: '程序', 语句: body }
});

module.exports.运行 = ({ 断言, 等于, 组名 }) => {
  组名('逃逸分析：不逃逸对象标量替换');

  // 点 p = {"x":1, "y":2}; 输出 p.x
  // p 只在函数内被读字段，不返回、不外传 -> 不逃逸 -> 标量替换
  const ast = { 类型: '程序', 语句: [
    声明('p', { 类型: '字典字面量',
      键: [{ 类型: '字面量', 值: 'x', 字面类型: '字符串' },
           { 类型: '字面量', 值: 'y', 字面类型: '字符串' }],
      值: [整(1), 整(2)] }),
    声明('px', 下标(标('p'), { 类型: '字面量', 值: 'x', 字面类型: '字符串' }))
  ]};
  const out = TS.编译(ast);
  断言(out.统计.标量替换数 >= 1, 'p 对象不逃逸，应被标量替换');

  // p.x 的下标访问应被改写成标量 p$x
  const pxDecl = ast.语句[1];
  等于(pxDecl.初始化.类型, '标识符', 'p.x 访问被改写为标量标识符');
  等于(pxDecl.初始化.名字, 'p$x', '标量名应为 p$x');

  组名('逃逸分析：返回的对象标记为逃逸');

  // 对象被 return -> 逃逸，不可标量替换
  const ast2 = { 类型: '程序', 语句: [
    函数('造点', [], [
      声明('p', { 类型: '字典字面量',
        键: [{ 类型: '字面量', 值: 'x', 字面类型: '字符串' }],
        值: [整(1)] }),
      返回(标('p'))
    ])
  ]};
  // 手动跑逃逸分析（不经过完整管线，避免函数表干扰）
  const 类型推断 = require('../类型推断');
  const 逃逸分析 = require('../逃逸分析');
  const ti = new 类型推断(ast2).分析();
  const ea = new 逃逸分析(ast2, ti).分析();
  断言(ea.逃逸总数 >= 1, '被返回的对象应标记为逃逸');
  等于(Object.keys(ea.标量替换表).length, 0, '逃逸对象不做标量替换');
};
