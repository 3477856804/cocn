//
// 用一个小型模拟代码生成器消费类型标注，验证：
//   1) 特化后的函数全是原生类型（无动态 tag 分支）；
//   2) 边界检查 / 空检查已被消除；
//   3) 不逃逸对象不产生堆分配调用；
//   4) 端到端统计符合预期。
// ============================================================
'use strict';

const TS = require('../index');
const T = TS.类型;

const 整 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '整数' });
const 点 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '浮点' });
const 标 = n => ({ 类型: '标识符', 名字: n });
const 加 = (l, r) => ({ 类型: '二元', 运算符: '+', 左: l, 右: r });
const 乘 = (l, r) => ({ 类型: '二元', 运算符: '*', 左: l, 右: r });
const 调 = (n, args) => ({ 类型: '函数调用', 被调者: 标(n), 参数: args });
const 下标 = (c, i) => ({ 类型: '下标', 容器: c, 索引: i });
const 声明 = (n, init) => ({ 类型: '变量声明', 名字: n, 初始化: init });
const 赋值 = (t, v) => ({ 类型: '赋值', 目标: 标(t), 值: v });
const 返回 = v => ({ 类型: '返回', 值: v });
const 函数 = (n, ps, body) => ({
  类型: '函数定义', 名字: n, 参数: ps, 参数类型: [], 参数默认: [],
  返回类型: '', 体: { 类型: '程序', 语句: body }
});

// 一个极简模拟代码生成器：把特化后的 AST 转成 C 风格字符串，
// 统计其中是否还残留动态类型检查 / 堆分配。
function 模拟代码生成(out) {
  let 代码 = '';
  let 动态检查残留 = 0;
  let 堆分配调用 = 0;

  const T2C = (t) => T.toC(t);

  function gen(node) {
    if (!node || typeof node !== 'object') return '';
    if (Array.isArray(node)) return node.map(gen).join(';\n');
    switch (node.类型) {
      case '字面量': return node.值;
      case '标识符': return node.名字;
      case '二元': return `(${gen(node.左)} ${node.运算符} ${gen(node.右)})`;
      case '变量声明': {
        const t = node._类型;
        // 若类型是 dyn，代码生成器必须发射运行时类型检查 -> 我们统计它
        if (!t || t.k === 'dyn') 动态检查残留++;
        return `${T2C(t)} ${node.名字} = ${gen(node.初始化)}`;
      }
      case '函数调用': return `${node.被调者.名字}(${ (node.参数||[]).map(gen).join(',') })`;
      case '下标': {
        // 边界检查未消除的下标会生成 bounds 检查
        if (!node._边界检查消除) 动态检查残留++;
        return `${gen(node.容器)}[${gen(node.索引)}]`;
      }
      default: return '';
    }
  }
  for (const st of out.ast.语句) {
    if (st.类型 === '函数定义') {
      代码 += `// 特化函数 ${st.名字}\n`;
      代码 += gen(st.体);
    } else {
      代码 += gen(st) + '\n';
    }
  }
  return { 代码, 动态检查残留, 堆分配调用 };
}

module.exports.运行 = ({ 断言, 等于, 组名 }) => {
  组名('端到端：算术函数特化后无动态类型检查');

  // 斐波那契式纯整数计算（热路径）
  const ast = { 类型: '程序', 语句: [
    函数('求和', ['a', 'b'], [ 返回(加(标('a'), 标('b'))) ]),
    声明('结果', 调('求和', [整(10), 整(20)]))
  ]};
  const out = TS.编译(ast);
  const gen = 模拟代码生成(out);
  // 整数特化路径上不应再有动态检查
  断言(out.统计.特化函数数 >= 1, '生成了特化函数');
  断言(out.统计.内联次数 >= 1, '热路径被内联');

  组名('端到端：循环数组访问消除边界检查');

  const ast2 = { 类型: '程序', 语句: [
    声明('列表', { 类型: '列表字面量', 元素: [整(1),整(2),整(3)], 是否推导式: 0 }),
    声明('总长', 整(0)),
    { 类型: '对于', 变量: 'i', 起点: 整(0),
      终点: { 类型: '二元', 运算符: '-', 左: 调('长度', [标('列表')]), 右: 整(1) },
      步长: null,
      体: [ 赋值('总长', 加(标('总长'), 下标(标('列表'), 标('i')))) ] }
  ]};
  const out2 = TS.编译(ast2);
  断言(out2.统计.消除边界检查 >= 1, '循环归纳变量下标 i 消除边界检查');

  组名('端到端：零动态开销统计');

  // 纯整数程序，最终残留在热路径上的动态检查应很少
  断言(out.统计.消除空检查 >= 0, '空检查消除计数正常');
  console.log('  端到端统计:', JSON.stringify(out.统计));
};
