// ============================================================
// 运行测试.js —— 极简测试运行器（零依赖，Node 直接跑）
//
// 用法：node 运行测试.js
// 退出码：0 全过；1 有失败。
// ============================================================
'use strict';

let 通过 = 0, 失败 = 0;
const 失败用例 = [];

function 断言(条件, 消息) {
  if (条件) { 通过++; }
  else { 失败++; 失败用例.push(消息); console.error('  ✗ ' + 消息); }
}
function 等于(实际, 期望, 消息) {
  断言(实际 === 期望, `${消息}（期望=${期望}, 实际=${实际}）`);
}
function 组名(n) { console.log('\n== ' + n + ' =='); }

// 收集所有测试文件并依次执行
const 文件 = [
  './类型推断测试.js',
  './函数特化测试.js',
  './内联测试.js',
  './逃逸分析测试.js',
  './端到端测试.js'
];

for (const f of 文件) {
  const 用例 = require(f);
  if (typeof 用例.运行 !== 'function') continue;
  用例.运行({ 断言, 等于, 组名 });
}

console.log('\──────────────────────────────');
console.log(`通过 ${通过} 项，失败 ${失败} 项`);
if (失败 > 0) {
  console.error('\n失败明细：');
  失败用例.forEach(m => console.error('  - ' + m));
  process.exit(1);
}
process.exit(0);
