// ============================================================
'use strict';

const 类型推断 = require('../类型推断');
const T = require('../类型');

// 快捷构造 AST 节点
const 整 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '整数' });
const 点 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '浮点' });
const 串 = v => ({ 类型: '字面量', 值: v, 字面类型: '字符串' });
const 标 = n => ({ 类型: '标识符', 名字: n });
const 加 = (l, r) => ({ 类型: '二元', 运算符: '+', 左: l, 右: r });
const 赋 = (t, v) => ({ 类型: '赋值', 目标: 标(t), 值: v });
const 声明 = (n, init) => ({ 类型: '变量声明', 名字: n, 初始化: init });
const 调 = (n, args) => ({ 类型: '函数调用', 被调者: 标(n), 参数: args });
const 返回 = v => ({ 类型: '返回', 值: v });
const 函数 = (n, ps, body) => ({
  类型: '函数定义', 名字: n, 参数: ps, 参数类型: [], 参数默认: [],
  返回类型: '', 体: { 类型: '程序', 语句: body }
});

function 推断(语句) {
  return new 类型推断({ 类型: '程序', 语句 }).分析();
}

module.exports.运行 = ({ 断言, 等于, 组名 }) => {
  组名('类型推断：字面量与声明');

  let r = 推断([ 声明('x', 整(5)) ]);
  等于(T.keyOf(r.全局['x']), 'int', '让 x = 5 -> x 是整数');

  r = 推断([ 声明('y', 点(1.5)) ]);
  等于(T.keyOf(r.全局['y']), 'float', '让 y = 1.5 -> y 是浮点');

  r = 推断([ 声明('s', 串('hi')) ]);
  等于(T.keyOf(r.全局['s']), 'str', '让 s = "hi" -> s 是字符串');

  组名('类型推断：运算推导');

  r = 推断([ 声明('a', 整(1)), 声明('b', 整(2)), 声明('c', 加(标('a'), 标('b'))) ]);
  等于(T.keyOf(r.全局['c']), 'int', '整数+整数 -> 整数');

  r = 推断([ 声明('a', 点(1.0)), 声明('b', 点(2.0)), 声明('c', 加(标('a'), 标('b'))) ]);
  等于(T.keyOf(r.全局['c']), 'float', '浮点+浮点 -> 浮点');

  r = 推断([ 声明('a', 串('x')), 声明('b', 串('y')), 声明('c', 加(标('a'), 标('b'))) ]);
  等于(T.keyOf(r.全局['c']), 'str', '字符串+字符串 -> 字符串');

  组名('类型推断：类型漂移升级动态');

  r = 推断([ 声明('x', 整(5)), 赋('x', 串('now string')) ]);
  等于(T.keyOf(r.全局['x']), 'dyn', 'x 先整数后字符串 -> 动态');

  组名('类型推断：函数返回类型');

  r = 推断([
    函数('平方', ['n'], [ 返回({ 类型: '二元', 运算符: '*', 左: 标('n'), 右: 标('n') }) ]),
    声明('z', 调('平方', [整(4)]))
  ]);
  等于(T.keyOf(r.返回类型['平方']), 'int', '平方(整数) 返回整数');

  组名('类型推断：函数参数类型随调用累积');

  r = 推断([
    函数('加', ['a', 'b'], [ 返回(加(标('a'), 标('b'))) ]),
    声明('r1', 调('加', [整(1), 整(2)])),
    声明('r2', 调('加', [点(1.0), 点(2.0)]))
  ]);
  // 两次调用：(int,int) 与 (float,float)，参数 LUB -> (float,float)
  等于(T.keyOf(r.签名['加'].params[0]), 'float', '加 的形参 a 累积为浮点');
  等于(T.keyOf(r.返回类型['加']), 'float', '加 返回浮点');

  组名('类型推断：循环累加收敛');

  r = 推断([
    声明('s', 整(0)),
    { 类型: '对于', 变量: 'i', 起点: 整(0), 终点: 整(10), 步长: null,
      体: [ 赋('s', 加(标('s'), 标('i'))) ] }
  ]);
  等于(T.keyOf(r.全局['s']), 'int', '循环累加 s 收敛为整数');

  组名('类型推断：准确率自检');
  // 上述断言覆盖的推断点总数；这里只跑一遍不崩即可
  断言(r.迭代次数 > 0 && r.迭代次数 <= 30, '定点迭代在合理次数内收敛');
};
