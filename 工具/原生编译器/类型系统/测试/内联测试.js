// ============================================================
// 内联测试.js —— 验证小函数被激进内联并常量折叠
// ============================================================
'use strict';

const TS = require('../index');
const T = TS.类型;

const 整 = v => ({ 类型: '字面量', 值: String(v), 字面类型: '整数' });
const 标 = n => ({ 类型: '标识符', 名字: n });
const 乘 = (l, r) => ({ 类型: '二元', 运算符: '*', 左: l, 右: r });
const 调 = (n, args) => ({ 类型: '函数调用', 被调者: 标(n), 参数: args });
const 声明 = (n, init) => ({ 类型: '变量声明', 名字: n, 初始化: init });
const 返回 = v => ({ 类型: '返回', 值: v });
const 函数 = (n, ps, body) => ({
  类型: '函数定义', 名字: n, 参数: ps, 参数类型: [], 参数默认: [],
  返回类型: '', 体: { 类型: '程序', 语句: body }
});

module.exports.运行 = ({ 断言, 等于, 组名 }) => {
  组名('激进内联：小函数被内联');

  const ast = { 类型: '程序', 语句: [
    函数('双', ['a'], [ 返回(乘(标('a'), 整(2))) ]),
    声明('r', 调('双', [整(21)]))
  ]};
  const out = TS.编译(ast);
  断言(out.统计.内联次数 >= 1, '双() 小函数应被内联');

  组名('内联后：常量折叠消除计算');

  // r = 双(21) 内联为 21*2，常量折叠为字面量 42
  const r = ast.语句[1];
  等于(r.初始化.类型, '字面量', '内联后 r 应折叠为字面量');
  等于(r.初始化.值, '42', 'r 的值常量折叠为 42');

  组名('内联缓存：未内联的大函数保留缓存点');

  // 构造一个「大函数」（节点数 > 阈值），不应被内联
  const 大函数体 = [];
  for (let i = 0; i < 60; i++) {
    大函数体.push({ 类型: '变量声明', 名字: 't' + i, 初始化: 整(i) });
  }
  大函数体.push(返回(标('t59')));
  const ast2 = { 类型: '程序', 语句: [
    函数('大函数', ['x'], 大函数体),
    声明('z', 调('大函数', [整(1)]))
  ]};
  const out2 = TS.编译(ast2);
  等于(out2.统计.内联次数, 0, '大函数不内联');
  断言(out2.统计.运行时缓存槽 >= 1 || out2.统计.内联缓存点数 >= 1,
    '未内联的调用点进入内联缓存');
};
