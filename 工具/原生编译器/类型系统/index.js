// ============================================================
// index.js —— coCN 原生编译器·类型系统主入口
//
// 把「动态类型 coCN 程序」转化为「静态类型、零运行时类型检查」的
// 特化 AST，交给下游代码生成器（另一个 agent）生成原生机器码。
//
// 管线阶段（顺序敏感）：
//   1) 类型推断      —— 数据流分析，给每个表达式标静态类型
//   2) 函数特化      —— 按实参类型组合拆出特化函数；容器布局特化
//   3) 激进内联      —— 小函数内联 + 常量折叠 + 内联缓存
//   4) 逃逸分析      —— 不逃逸对象标量替换 / 栈分配
//   5) 检查消除      —— 数组边界检查消除 + 空检查消除
//   6) 特化缓存      —— 未能静态特化的调用点登记运行时缓存槽
//
// 输入：AST（JSON，节点用「类型」字段标识）。
// 输出：{ ast(标注后), 类型信息, 统计 } —— 代码生成器消费。
// ============================================================

'use strict';

const T = require('./类型');
const 类型推断 = require('./类型推断');
const 函数特化 = require('./函数特化');
const 内联 = require('./内联');
const 逃逸分析 = require('./逃逸分析');
const 检查消除 = require('./检查消除');
const 特化缓存 = require('./特化缓存');

/**
 * 对一个 coCN AST 跑完整的类型特化管线。
 * @param {object} ast 程序节点 {类型:'程序', 语句:[...]}
 * @param {{详细?:boolean}} [选项]
 * @returns {{ast:object, 类型信息:object, 统计:object}}
 */
function 编译(ast, 选项 = {}) {
  const 计时 = {};
  const t0 = process.hrtime.bigint();

  // ---- 阶段 1：类型推断 ----
  const 推断 = new 类型推断(ast);
  const 推断结果 = 推断.分析();
  计时.类型推断 = 推断.迭代次数;

  // ---- 阶段 2：函数特化 + 数据结构特化 ----
  const 特化 = new 函数特化(ast, 推断结果);
  const 特化结果 = 特化.特化();
  const 结构布局 = 函数特化.特化数据结构(ast, 推断结果);

  // ---- 阶段 3：激进内联 + 内联后优化 ----
  const 内联器 = new 内联(ast, 特化结果);
  const 内联结果 = 内联器.执行();
  内联器.内联后优化();

  // ---- 阶段 4：逃逸分析 + 标量替换 ----
  const 逃逸 = new 逃逸分析(ast, 推断结果);
  const 逃逸结果 = 逃逸.分析();

  // ---- 阶段 5：边界检查 + 空检查消除 ----
  const 检查 = new 检查消除(ast, 推断结果);
  const 检查结果 = 检查.执行();

  // ---- 阶段 6：特化缓存（运行时反馈槽位） ----
  const 缓存 = new 特化缓存(ast, 推断结果);
  const 缓存槽 = 缓存.登记();

  const t1 = process.hrtime.bigint();
  const 统计 = {
    耗时毫秒: Number(t1 - t0) / 1e6,
    类型推断迭代: 计时.类型推断,
    特化函数数: Object.keys(特化结果.特化函数表).length,
    内联次数: 内联结果.内联次数,
    内联缓存点数: 内联结果.内联缓存.length,
    逃逸对象数: 逃逸结果.逃逸总数,
    标量替换数: 逃逸结果.可标量替换数,
    消除边界检查: 检查结果.消除边界检查数,
    消除空检查: 检查结果.消除空检查数,
    运行时缓存槽: 缓存槽.length
  };

  return {
    ast,
    类型信息: {
      签名: 推断结果.签名,
      返回类型: 推断结果.返回类型,
      全局: 推断结果.全局,
      结构体: 推断.结构体 || {},
      类: 推断.类 || {}
    },
    统计
  };
}

module.exports = {
  编译,
  // 暴露各子模块，便于测试与单独复用
  类型: T,
  类型推断,
  函数特化,
  内联,
  逃逸分析,
  检查消除,
  特化缓存
};
