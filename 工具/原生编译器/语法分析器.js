// ============================================================
// 语法分析器.js —— coCN 递归下降语法分析器（Node.js 移植版）
//
// 输入：词法分析器产出的 token 数组
// 输出：AST 程序节点 { 类型:"程序", 语句:[...] }
//
// 支持第一版语法子集：变量声明/赋值、算术、比较、逻辑、
//   如果/否则、当循环、对于循环、函数定义/调用/返回、
//   列表、字典、下标、字符串拼接。
// （类/枚举/结构体/匹配/并发/尝试 等高级特性暂不支持，报错即可。）
// ============================================================

const { 词法分析 } = require("./词法分析器.js");

let g_tokens = [];
let g_pos = 0;

function 词类() {
  if (g_pos >= g_tokens.length) return "文件结束";
  return g_tokens[g_pos].类型;
}
function 词值() {
  if (g_pos >= g_tokens.length) return "";
  return g_tokens[g_pos].值;
}
function 行号() {
  if (g_pos >= g_tokens.length) return 0;
  return g_tokens[g_pos].行;
}
function 前进() { g_pos++; }

function 报错(msg) {
  throw new Error(
    `语法错误 (第${行号()}行): ${msg}，得到 '${词值()}'`
  );
}

function 期望关键字(k) {
  if (词类() !== "关键字" || 词值() !== k) 报错(`期望关键字 '${k}'`);
  前进();
}
function 期望运算符(op) {
  if (词类() !== "运算符" || 词值() !== op) 报错(`期望运算符 '${op}'`);
  前进();
}

function 是类型关键字(k) {
  return k === "整数" || k === "浮点" || k === "布尔" ||
         k === "字符串" || k === "列表" || k === "字典";
}
// 复合赋值运算符（+= 脱糖为 x = x + e，与 src/语法分析器.co 保持一致）
const 复合赋值表 = {
  "+=": "+", "-=": "-", "*=": "*", "/=": "/", "%=": "%", "//=": "//",
  "**=": "**", "&=": "&", "|=": "|", "^=": "^", "<<=": "<<", ">>=": ">>",
};
function 是复合赋值(v) { return 复合赋值表[v] !== undefined; }
function 是结束() {
  return 词类() === "关键字" && 词值() === "结束";
}
function 是分支头() {
  if (词类() !== "关键字") return false;
  const v = 词值();
  return v === "否则" || v === "否则如果" || v === "否则若";
}
function 是语句结束() {
  return 词类() === "换行" || 词类() === "文件结束" || 是结束() || 是分支头();
}
// 真换行才算行尾；分号产生的「换行」只是语句分隔，单行循环体继续收集
function 是行尾() {
  return (词类() === "换行" && 词值() !== ";") || 词类() === "文件结束";
}
// 花括号块里的语句收集同样按行尾停止：} 视为块的行尾
function 是右括号() {
  return 词类() === "运算符" && 词值() === "}";
}
// 括号深度：花括号块内换行不算「行尾」，且单行 如果 体遇到 ; 就收尾
// （块外的老写法保持原语义，避免回归）。
let 括号深度 = 0;

// 花括号块：{ 语句 ; 语句 ; ... } —— 中文紧凑写法的关键糖。
// 块内换行/分号等价，因此一条逻辑可以压成一行。
function 解析花括号块(上下文) {
  前进(); // 吃掉 {
  括号深度++;
  const 体 = [];
  while (词类() !== "文件结束" && !是右括号()) {
    if (词类() === "换行") { 前进(); continue; }
    const st = 解析语句();
    if (st === null) continue;
    体.push(st);
  }
  if (!是右括号()) 报错(上下文 + " 的花括号块缺少 }");
  前进(); // 吃掉 }
  括号深度--;
  return 体;
}
function 是则() {
  return 词类() === "关键字" && (词值() === "则" || 词值() === "那么");
}
function 跳过换行() {
  while (词类() === "换行") 前进();
}

// ---------------- 表达式层 ----------------

function 解析主要() {
  if (词类() === "整数") {
    const n = { 类型: "字面量", 值: 词值(), 字面类型: "整数" };
    前进(); return n;
  }
  if (词类() === "浮点") {
    const n = { 类型: "字面量", 值: 词值(), 字面类型: "浮点" };
    前进(); return n;
  }
  if (词类() === "字符串") {
    const n = { 类型: "字面量", 值: 词值(), 字面类型: "字符串" };
    前进(); return n;
  }
  if (词类() === "关键字" && 词值() === "真") {
    前进(); return { 类型: "字面量", 值: "1", 字面类型: "布尔" };
  }
  if (词类() === "关键字" && 词值() === "假") {
    前进(); return { 类型: "字面量", 值: "0", 字面类型: "布尔" };
  }
  if (词类() === "关键字" && 词值() === "空") {
    前进(); return { 类型: "字面量", 值: "", 字面类型: "空" };
  }
  if (词类() === "标识符") {
    const n = { 类型: "标识符", 名字: 词值() };
    前进(); return n;
  }
  if (词类() === "运算符" && 词值() === "(") {
    前进();
    if (词类() === "运算符" && 词值() === ")") {
      前进();
      return { 类型: "元组字面量", 元素: [] };
    }
    const 首个 = 解析或();
    if (词类() === "运算符" && 词值() === ",") {
      const 元素 = [首个];
      while (词类() === "运算符" && 词值() === ",") {
        前进();
        if (词类() === "运算符" && 词值() === ")") break;
        元素.push(解析或());
      }
      期望运算符(")");
      return { 类型: "元组字面量", 元素 };
    }
    期望运算符(")");
    return 首个;
  }
  if (词类() === "运算符" && 词值() === "[") return 解析列表字面量();
  if (词类() === "运算符" && 词值() === "{") return 解析字典字面量();
  if (词类() === "关键字" && 词值() === "函数") 报错("匿名函数暂不支持");
  if (词类() === "关键字" && 词值() === "匹配") 报错("匹配暂不支持");
  if (词类() === "关键字" && 词值() === "并发") 报错("并发暂不支持");
  if (词类() === "关键字" && 词值() === "等待") 报错("等待暂不支持");
  if (词类() === "关键字" && (词值() === "self" || 词值() === "自己")) {
    const n = { 类型: "标识符", 名字: 词值() };
    前进(); return n;
  }
  if (是结束()) 报错("多余的 '结束'");
  报错("意外的表达式记号");
}

function 解析列表字面量() {
  前进(); // [
  if (词类() === "运算符" && 词值() === "]") {
    前进();
    return { 类型: "列表字面量", 元素: [], 是否推导式: 0 };
  }
  const 首个 = 解析或();
  if (词类() === "关键字" && 词值() === "对于") {
    // 列表推导式，暂不支持
    报错("列表推导式暂不支持");
  }
  const 元素 = [首个];
  while (词类() === "运算符" && 词值() === ",") {
    前进();
    if (词类() === "运算符" && 词值() === "]") break;
    元素.push(解析或());
  }
  期望运算符("]");
  return { 类型: "列表字面量", 元素, 是否推导式: 0 };
}

function 解析字典字面量() {
  前进(); // {
  if (词类() === "运算符" && 词值() === "}") {
    前进();
    return { 类型: "字典字面量", 键: [], 值: [] };
  }
  const 键 = [], 值 = [];
  while (词类() !== "文件结束") {
    if (词类() === "运算符" && 词值() === "}") break;
    let k;
    if (词类() === "字符串") {
      k = { 类型: "字面量", 值: 词值(), 字面类型: "字符串" };
      前进();
    } else {
      k = 解析或();
      if (k.类型 === "标识符") {
        k = { 类型: "字面量", 值: k.名字, 字面类型: "字符串" };
      }
    }
    期望运算符(":");
    const v = 解析或();
    键.push(k); 值.push(v);
    if (词类() === "运算符" && 词值() === ",") 前进();
  }
  期望运算符("}");
  return { 类型: "字典字面量", 键, 值 };
}

function 解析后缀() {
  let n = 解析主要();
  let 变 = 1;
  while (变 === 1) {
    let 消费 = 0;
    if (词类() === "运算符" && 词值() === "(") {
      消费 = 1; 前进();
      const 参数 = [];
      if (!(词类() === "运算符" && 词值() === ")")) {
        while (true) {
          参数.push(解析或());
          if (词类() === "运算符" && 词值() === ",") { 前进(); continue; }
          break;
        }
      }
      期望运算符(")");
      n = { 类型: "函数调用", 被调者: n, 参数 };
    }
    if (词类() === "运算符" && 词值() === "[") {
      消费 = 1; 前进();
      const idx = 解析或();
      期望运算符("]");
      n = { 类型: "下标", 容器: n, 索引: idx };
    }
    if (词类() === "运算符" && 词值() === ".") {
      消费 = 1; 前进();
      if (词类() !== "标识符") 报错("成员访问 '.' 后需要标识符");
      const 成员名 = 词值();
      前进();
      n = { 类型: "下标", 容器: n, 索引: { 类型: "字面量", 值: 成员名, 字面类型: "字符串" } };
    }
    if (消费 === 0) 变 = 0;
  }
  return n;
}

function 解析一元() {
  if (词类() === "运算符" && (词值() === "-" || 词值() === "+")) {
    const op = 词值(); 前进();
    return { 类型: "一元", 运算符: op, 操作数: 解析一元() };
  }
  if (词类() === "关键字" && 词值() === "非") {
    前进();
    return { 类型: "一元", 运算符: "非", 操作数: 解析一元() };
  }
  if (词类() === "运算符" && 词值() === "~") {
    前进();
    return { 类型: "一元", 运算符: "~", 操作数: 解析一元() };
  }
  return 解析后缀();
}

function 解析幂() {
  const 左 = 解析一元();
  if (词类() === "运算符" && 词值() === "**") {
    前进();
    const 右 = 解析幂();
    return { 类型: "二元", 运算符: "**", 左, 右 };
  }
  return 左;
}

function 解析乘除模() {
  let 左 = 解析幂();
  while (true) {
    let op = "";
    if (词类() === "运算符" && (词值() === "*" || 词值() === "/" || 词值() === "%" || 词值() === "//")) {
      op = 词值();
    }
    if (op === "") break;
    前进();
    左 = { 类型: "二元", 运算符: op, 左, 右: 解析幂() };
  }
  return 左;
}

function 解析加减() {
  let 左 = 解析乘除模();
  while (true) {
    let op = "";
    if (词类() === "运算符" && (词值() === "+" || 词值() === "-")) op = 词值();
    if (op === "") break;
    前进();
    左 = { 类型: "二元", 运算符: op, 左, 右: 解析乘除模() };
  }
  return 左;
}

function 解析移位() {
  let 左 = 解析加减();
  while (true) {
    let op = "";
    if (词类() === "运算符" && (词值() === "<<" || 词值() === ">>")) op = 词值();
    if (op === "") break;
    前进();
    左 = { 类型: "二元", 运算符: op, 左, 右: 解析加减() };
  }
  return 左;
}

function 解析关系() {
  let 左 = 解析移位();
  while (true) {
    let op = "";
    if (词类() === "运算符" && (词值() === "<" || 词值() === ">" || 词值() === "<=" || 词值() === ">=")) op = 词值();
    if (op === "") break;
    前进();
    左 = { 类型: "二元", 运算符: op, 左, 右: 解析移位() };
  }
  return 左;
}

function 解析相等() {
  let 左 = 解析关系();
  while (true) {
    let op = "";
    if (词类() === "运算符" && (词值() === "==" || 词值() === "!=")) op = 词值();
    if (op === "") break;
    前进();
    左 = { 类型: "二元", 运算符: op, 左, 右: 解析关系() };
  }
  return 左;
}

function 解析位与() {
  let 左 = 解析相等();
  while (词类() === "运算符" && 词值() === "&") {
    前进();
    左 = { 类型: "二元", 运算符: "&", 左, 右: 解析相等() };
  }
  return 左;
}
function 解析位异或() {
  let 左 = 解析位与();
  while (词类() === "运算符" && 词值() === "^") {
    前进();
    左 = { 类型: "二元", 运算符: "^", 左, 右: 解析位与() };
  }
  return 左;
}
function 解析位或() {
  let 左 = 解析位异或();
  while (词类() === "运算符" && 词值() === "|") {
    前进();
    左 = { 类型: "二元", 运算符: "|", 左, 右: 解析位异或() };
  }
  return 左;
}

function 解析且() {
  let 左 = 解析位或();
  while (词类() === "关键字" && 词值() === "且") {
    前进();
    左 = { 类型: "二元", 运算符: "且", 左, 右: 解析位或() };
  }
  return 左;
}
function 解析或() {
  let 左 = 解析且();
  while (词类() === "关键字" && 词值() === "或") {
    前进();
    左 = { 类型: "二元", 运算符: "或", 左, 右: 解析且() };
  }
  return 左;
}

// ---------------- 语句层 ----------------

function 解析变量声明() {
  let 标注 = "";
  const 头 = 词值();
  if (头 === "让" || 头 === "变量" || 头 === "常量") 前进();
  if (词类() === "关键字" && 是类型关键字(词值())) {
    标注 = 词值(); 前进();
  }
  if (词类() !== "标识符") 报错("变量声明需要标识符");
  const 名 = 词值(); 前进();
  let 初始化 = null;
  if (词类() === "运算符" && 词值() === "=") {
    前进();
    初始化 = 解析或();
  }
  return { 类型: "变量声明", 名字: 名, 类型标注: 标注, 初始化 };
}

function 解析返回() {
  前进();
  let v = null;
  if (词类() !== "换行" && 词类() !== "文件结束" && !是结束() && !是分支头()) {
    v = 解析或();
  }
  return { 类型: "返回", 值: v };
}

function 解析如果() {
  前进(); // 如果/若
  const 条件 = 解析或();
  if (是则()) 前进();
  let 块形式 = 0;
  if (词类() === "换行") 块形式 = 1;
  const 则体 = 解析分支体();
  const 否则链 = [];
  while (是分支头()) {
    let 分支条件 = null;
    const v = 词值();
    if (v === "否则如果" || v === "否则若") {
      前进();
      分支条件 = 解析或();
    }
    if (v === "否则") {
      前进();
      if (词类() === "关键字" && (词值() === "如果" || 词值() === "若")) {
        前进();
        分支条件 = 解析或();
      }
    }
    if (是则()) 前进();
    const 分支体 = 解析分支体();
    否则链.push({ 条件: 分支条件, 体: 分支体 });
  }
  if (块形式 === 1) {
    if (!是结束()) 报错("如果 块缺少 结束");
    前进();
  } else {
    if (是结束()) 前进();
  }
  return { 类型: "如果", 条件, 则体, 否则链 };
}

function 解析分支体() {
  const 体 = [];
  // 花括号块形式：`如果 条件 { 语句; 语句 }`
  if (词类() === "运算符" && 词值() === "{") return 解析花括号块("分支");
  let 块形式 = 0;
  if (词类() === "换行") 块形式 = 1;
  if (块形式 === 1) {
    while (词类() !== "文件结束") {
      if (词类() === "换行") { 前进(); continue; }
      if (是分支头() || 是结束()) break;
      const st = 解析语句();
      if (st !== null) 体.push(st);
    }
  } else {
    // 单行形式：`如果 条件 则 语句` —— 只取一条语句。
    // 分号属于外层（块或行），不能被吸收进分支体，否则
    // `{如果 n<2 则 返回 n;返回 …}` 会把第二个返回错当 then 体。
    if (括号深度 === 0) 跳过换行();
    if (!(是分支头() || 是结束() || 是行尾() || 是右括号())) {
      const st = 解析语句();
      if (st !== null) 体.push(st);
    }
  }
  return 体;
}

// 循环体：块形式（循环 后换行 … 结束）与单行形式（循环 后同行语句，可用 ; 串联，
// 结尾的 结束 可写可不写）。与 src/语法分析器.co 的 解析循环体 一致。
function 解析循环体() {
  // 花括号块形式：`循环 { … }` —— 结尾的 结束 不需要
  if (词类() === "运算符" && 词值() === "{") return 解析花括号块("循环");
  // 空块：循环 后紧跟 结束
  if (是结束()) { 前进(); return []; }
  // 单行形式：循环 后整行都是循环体
  if (词类() !== "换行") {
    const 单行体 = [];
    while (词类() !== "文件结束" && !是结束() && !是分支头() && !是行尾()) {
      if (词类() === "换行") { 前进(); continue; }  // 分号分隔
      const st = 解析语句();
      if (st !== null) 单行体.push(st);
    }
    if (是结束()) 前进();
    return 单行体;
  }
  // 块形式
  前进(); // 吃掉换行
  const 体 = [];
  while (!是结束() && 词类() !== "文件结束") {
    if (词类() === "换行") { 前进(); continue; }
    const st = 解析语句();
    if (st !== null) 体.push(st);
  }
  if (!是结束()) 报错("循环缺少 结束");
  前进();
  return 体;
}

function 解析当() {
  前进();
  const 条件 = 解析或();
  期望关键字("循环");
  const 体 = 解析循环体();
  return { 类型: "当", 条件, 体 };
}

function 解析对于() {
  前进();
  if (词类() === "关键字" && 是类型关键字(词值())) 前进();
  if (词类() !== "标识符") 报错("对于 循环需要标识符");
  const 变量名 = 词值(); 前进();
  // for-each
  if (词类() === "关键字" && (词值() === "在" || 词值() === "于")) {
    前进();
    const 容器节点 = 解析或();
    期望关键字("循环");
    const 体 = [];
    while (!是结束() && 词类() !== "文件结束") {
      if (词类() === "换行") { 前进(); continue; }
      const st = 解析语句();
      if (st !== null) 体.push(st);
    }
    if (!是结束()) 报错("对于 循环缺少 结束");
    前进();
    return { 类型: "对于", 变量: 变量名, 遍历源: 容器节点, 体, 是否遍历: 1 };
  }
  // 范围形式
  期望关键字("从");
  const 起点 = 解析或();
  期望关键字("到");
  const 终点 = 解析或();
  let 步长值 = null;
  if (词类() === "关键字" && 词值() === "步长") {
    前进();
    步长值 = 解析或();
  }
  期望关键字("循环");
  const 体 = 解析循环体();
  return { 类型: "对于", 变量: 变量名, 起点, 终点, 步长: 步长值, 体 };
}

function 解析函数定义() {
  前进();
  if (词类() !== "标识符") 报错("函数定义需要名字");
  const 名 = 词值(); 前进();
  期望运算符("(");
  const 参数 = [], 参数类型 = [], 参数默认 = [];
  if (!(词类() === "运算符" && 词值() === ")")) {
    while (!(词类() === "运算符" && 词值() === ")") && 词类() !== "文件结束") {
      let pt = "";
      if (词类() === "关键字" && 是类型关键字(词值())) { pt = 词值(); 前进(); }
      let 可变 = false;
      if (词类() === "运算符" && 词值() === "...") { 可变 = true; 前进(); }
      if (词类() !== "标识符" && !(词类() === "关键字" && (词值() === "self" || 词值() === "自己"))) {
        报错("函数参数需要标识符");
      }
      参数.push(词值());
      参数类型.push(可变 ? "可变" : pt);
      前进();
      let 默认值 = null;
      if (词类() === "运算符" && 词值() === "=") { 前进(); 默认值 = 解析或(); }
      参数默认.push(默认值);
      if (词类() === "运算符" && 词值() === ",") 前进();
    }
  }
  期望运算符(")");
  let 返回类型 = "";
  if (词类() === "运算符" && 词值() === "->") {
    前进();
    if (词类() === "关键字" && 是类型关键字(词值())) {
      返回类型 = 词值(); 前进();
    } else {
      报错("函数返回类型标注无效");
    }
  }
  // 花括号块形式：函数 名(...){ 语句; 语句 } —— 不需要结尾 结束
  if (词类() === "运算符" && 词值() === "{") {
    const 花体 = { 类型: "程序", 语句: 解析花括号块("函数定义") };
    return { 类型: "函数定义", 名字: 名, 参数, 参数类型, 参数默认, 返回类型, 体: 花体 };
  }
  const 体语句 = [];
  while (!是结束() && 词类() !== "文件结束") {
    if (词类() === "换行") { 前进(); continue; }
    const st = 解析语句();
    if (st !== null) 体语句.push(st);
  }
  if (!是结束()) 报错("函数定义缺少 结束");
  前进();
  const 体 = { 类型: "程序", 语句: 体语句 };
  return { 类型: "函数定义", 名字: 名, 参数, 参数类型, 参数默认, 返回类型, 体 };
}

function 解析语句() {
  if (词类() === "换行") { 前进(); return null; }
  if (词类() === "文件结束") return null;
  if (词类() === "关键字") {
    const k = 词值();
    if (k === "让" || k === "变量" || k === "常量") return 解析变量声明();
    if (是类型关键字(k)) return 解析变量声明();
    if (k === "函数") return 解析函数定义();
    if (k === "返回") return 解析返回();
    if (k === "如果" || k === "若") return 解析如果();
    if (k === "当") return 解析当();
    if (k === "对于") return 解析对于();
    if (k === "跳出") { 前进(); return { 类型: "跳出" }; }
    if (k === "继续") { 前进(); return { 类型: "继续" }; }
    if (k === "抛出") { 前进(); return { 类型: "抛出", 值: 解析或() }; }
    if (k === "导入") {
      前进();
      if (词类() !== "字符串") 报错("导入需要字符串路径");
      const p = 词值(); 前进();
      return { 类型: "导入", 路径: p };
    }
    if (k === "枚举" || k === "结构体" || k === "类" || k === "尝试" || k === "匹配") {
      报错(`'${k}' 暂不支持`);
    }
  }
  const 左 = 解析或();
  if (词类() === "运算符" && 词值() === "=") {
    前进();
    const v = 解析或();
    return { 类型: "赋值", 目标: 左, 值: v };
  }
  // 复合赋值：x += e 脱糖为 x = x + e（目标可以是标识符或下标）
  if (词类() === "运算符" && 是复合赋值(词值())) {
    const op = 复合赋值表[词值()];
    前进();
    const 右 = 解析或();
    return { 类型: "赋值", 目标: 左, 值: { 类型: "二元", 运算符: op, 左, 右 } };
  }
  // 命令式无括号调用：输出 x ／ 输出 a, b, c
  if (左.类型 === "标识符" && !是语句结束()) {
    const 参数 = [解析或()];
    while (词类() === "运算符" && 词值() === ",") {
      前进();
      参数.push(解析或());
    }
    return { 类型: "函数调用", 被调者: 左, 参数 };
  }
  return 左;
}

function 语法分析(tokens) {
  g_tokens = tokens;
  g_pos = 0;
  const 语句表 = [];
  while (词类() !== "文件结束") {
    const st = 解析语句();
    if (st !== null) 语句表.push(st);
  }
  return { 类型: "程序", 语句: 语句表 };
}

function 解析源(源) {
  const tokens = 词法分析(源);
  return 语法分析(tokens);
}

