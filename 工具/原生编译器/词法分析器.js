// ============================================================
// 词法分析器.js —— coCN 原生编译器前端（Node.js 移植版）
//
// 导出：函数 词法分析(源 字符串) -> token 数组
// 每个 token：{ 类型, 值, 行, 列 }
// 类型："整数" | "浮点" | "字符串" | "标识符" | "关键字" | "运算符" | "换行" | "文件结束"
//
// 移植自 src/词法分析器.co，语义保持一致。
// ============================================================

// 是否为十进制数字字符
function 是数字(c) {
  return c >= "0" && c <= "9";
}

// 操作符字符首字符集合
const 操作符字符集 = new Set(
  "+-*/%=!<>()[]{}:,&|^~.;".split("")
);

// 多字符运算符（必须按长度递减尝试，否则 <<= 会被 << 抢先吃掉）
const 多字符运算符 = [
  "...", "<<=", ">>=", "//=", "**=",
  "+=", "-=", "*=", "/=", "%=", "&=", "|=", "^=",
  "->", "**", "//", "==", "!=", "<=", ">=", "<<", ">>",
];

// 关键字集合（与 src/词法分析器.co 的 是关键字 保持一致）
const 关键字集 = new Set([
  "让", "整数", "浮点", "布尔", "字符串", "列表", "字典", "变量", "常量",
  "函数", "返回", "如果", "否则", "否则如果", "否则若", "若", "当", "对于", "从", "到", "步长",
  "循环", "结束", "跳出", "继续", "真", "假", "且", "或", "非", "导入",
  "匹配", "是", "情况", "默认", "于", "在", "那么", "尝试", "捕获", "最终", "抛出",
  "并发", "等待", "则", "枚举", "结构体", "作为", "类", "继承", "继承自",
  "self", "自己", "super", "空",
]);

// 类型别名：只保留「串」这一个单字别名。
// 曾经试过 表/数组/映射/文本，但它们都是很好的普通变量名，
// 一旦被认成关键字，`列表 表 = []` 这种写法当场崩掉——别名收益小、误伤面大。
// 「串」在两条通道上的支持情况由 src/语法分析器.co 与引导器决定，
// 引导器（v0.1.0 C 引导二进制）不认 串，所以这里也不认，保持双通道一致。

// 中文位运算别名 -> 符号运算符
const 位运算别名 = {
  "按位与": "&", "按位或": "|", "按位异或": "^", "按位取反": "~",
  "左移": "<<", "右移": ">>",
};

function 词法分析(源) {
  // 按码点切分，保证 UTF-8/中文列号正确
  const chars = Array.from(源);
  const n = chars.length;
  const 表 = [];
  let p = 0;
  let 行 = 1;
  let 列 = 1;
  let 行有内容 = 0;

  while (p < n) {
    const c = chars[p];

    // 空白
    if (c === " " || c === "\t" || c === "\r") {
      p++; 列++;
      continue;
    }
    // 注释 # 到行尾
    if (c === "#") {
      while (p < n && chars[p] !== "\n") { p++; 列++; }
      continue;
    }
    // 分号：语句分隔符，与换行同义（一行多语句：整数 a = 1; 整数 b = 2）
    // token 值记 ";"，解析器据此区分「真换行」与「分号」——单行循环体不被分号截断。
    if (c === ";") {
      if (行有内容 === 1) {
        表.push({ 类型: "换行", 值: ";", 行, 列 });
      }
      p++; 列++;
      continue;
    }

    // 换行
    if (c === "\n") {
      if (行有内容 === 1) {
        表.push({ 类型: "换行", 值: "\n", 行, 列 });
      }
      行++; 列 = 1; p++;
      行有内容 = 0;
      continue;
    }

    // 数字
    if (是数字(c)) {
      const 记行 = 行, 记列 = 列, 起 = p;
      let 浮 = false;
      while (p < n && 是数字(chars[p])) { p++; 列++; }
      // 小数
      if (p + 1 < n && chars[p] === "." && 是数字(chars[p + 1])) {
        浮 = true; p++; 列++;
        while (p < n && 是数字(chars[p])) { p++; 列++; }
      }
      // 科学计数
      if (p < n && (chars[p] === "e" || chars[p] === "E")) {
        let q = p + 1;
        if (q < n && (chars[q] === "+" || chars[q] === "-")) q++;
        if (q < n && 是数字(chars[q])) {
          浮 = true; p++; 列++;
          if (p < n && (chars[p] === "+" || chars[p] === "-")) { p++; 列++; }
          while (p < n && 是数字(chars[p])) { p++; 列++; }
        }
      }
      const 词 = chars.slice(起, p).join("");
      // 整数字面量范围闸：文案与判定逐字对齐宿主（词法错误 (第R行,C列): 整数字面量超出范围）。
      // 0.1.16 审计实测：99999999999999999999 在这里静默编成
      // movabs 的 imm64 截断值 776679631452241919 并正常打印（rc=0）——
      // 「编得过、跑得动、但结果是错的」，正是项目红线点名的形态。
      // 浮点分支不受影响（浮点在生成器里本来就编译期拒绝）。
      if (!浮 && BigInt(词) > 9223372036854775807n)
        throw new Error(`词法错误 (第${记行}行,${记列}列): 整数字面量超出范围`);
      表.push({ 类型: 浮 ? "浮点" : "整数", 值: 词, 行: 记行, 列: 记列 });
      行有内容 = 1;
      continue;
    }

    // 字符串
    if (c === "\"") {
      const 记行 = 行, 记列 = 列;
      p++; 列++;
      let 内容 = "";
      while (p < n && chars[p] !== "\"") {
        if (chars[p] === "\\" && p + 1 < n) {
          const e = chars[p + 1];
          if (e === "n") 内容 += "\n";
          else if (e === "t") 内容 += "\t";
          else if (e === "\"") 内容 += "\"";
          else if (e === "\\") 内容 += "\\";
          else 内容 += e;
          p += 2; 列 += 2;
        } else {
          内容 += chars[p]; p++; 列++;
        }
      }
      if (p < n && chars[p] === "\"") { p++; 列++; }
      表.push({ 类型: "字符串", 值: 内容, 行: 记行, 列: 记列 });
      行有内容 = 1;
      continue;
    }

    // 运算符（贪婪最长匹配：先试 3 字符再 2 字符，避免 <<= 被 << 吃掉）
    if (操作符字符集.has(c)) {
      const 记行 = 行, 记列 = 列;
      let 词 = "";
      for (const m of 多字符运算符) {
        let 命中 = true;
        for (let k = 0; k < m.length; k++) {
          if (p + k >= n || chars[p + k] !== m[k]) { 命中 = false; break; }
        }
        if (命中) { 词 = m; break; }
      }
      if (词) { p += 词.length; 列 += 词.length; }
      else { 词 = c; p++; 列++; }
      表.push({ 类型: "运算符", 值: 词, 行: 记行, 列: 记列 });
      行有内容 = 1;
      continue;
    }

    // 标识符 / 关键字
    const 记行 = 行, 记列 = 列, 起 = p;
    while (p < n) {
      const cc = chars[p];
      if (cc === " " || cc === "\t" || cc === "\r" || cc === "\n") break;
      if (cc === "#" || cc === "\"") break;
      if (操作符字符集.has(cc)) break;
      p++; 列++;
    }
    const 词 = chars.slice(起, p).join("");
    if (位运算别名[词]) {
      表.push({ 类型: "运算符", 值: 位运算别名[词], 行: 记行, 列: 记列 });

    } else if (关键字集.has(词)) {
      表.push({ 类型: "关键字", 值: 词, 行: 记行, 列: 记列 });
    } else {
      表.push({ 类型: "标识符", 值: 词, 行: 记行, 列: 记列 });
    }
    行有内容 = 1;
  }

  表.push({ 类型: "文件结束", 值: "", 行, 列 });
  return 表;
}

module.exports = { 词法分析 };
