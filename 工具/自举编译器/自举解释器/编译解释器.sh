#!/bin/bash
# ============================================================
# 编译解释器.sh —— 简化版解释器编译与测试脚本
#
# 功能：
#   1. 拼接所有组件为合并文件
#   2. 用 coCN eval 后端运行测试（验证解释器逻辑正确）
#   3. 用自举编译器前端解析各组件源码（验证自举编译器能处理复杂程序）
#   4. 端到端测试：用主入口读取文件并运行
#
# 用法：
#   bash 工具/自举编译器/自举解释器/编译解释器.sh
# ============================================================

DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$DIR/../../.." && pwd)"

PASS=0
FAIL=0

echo "============================================"
echo "  简化解释器编译与验证"
echo "============================================"
echo ""

# ============================================================
# 步骤 1：拼接组件并运行测试
# ============================================================
echo ">>> 步骤 1：拼接组件并运行测试程序"
echo ""

TMP="/tmp/自举解释器_合并_$$.co"

cat "$DIR/词法.co" \
    "$DIR/语法.co" \
    "$DIR/求值.co" \
    "$DIR/测试.co" > "$TMP"

echo "合并文件: $TMP"
echo "文件大小: $(wc -l < "$TMP") 行"
echo ""

echo "--- 运行测试 ---"
COCN_BACKEND=eval node "$PROJECT_ROOT/bin/cocn.js" "$TMP"
echo ""

# ============================================================
# 步骤 2：用自举编译器前端解析各组件（验证能编译复杂程序）
# ============================================================
echo ">>> 步骤 2：用自举编译器前端解析各组件源码"
echo ""

BOOT_DIR="$PROJECT_ROOT/工具/自举编译器"

# 逐个解析我们的组件
for f in 词法.co 语法.co 求值.co 主.co 测试.co; do
    echo "--- 解析 $f ---"
    SRC_PATH="$DIR/$f"
    LINE_COUNT=$(wc -l < "$SRC_PATH")
    echo "  源码行数: $LINE_COUNT"

    OUT="/tmp/ast_${f%.co}.json"
    if bash "$BOOT_DIR/编译.sh" "$SRC_PATH" "$OUT" 2>/dev/null; then
        AST_SIZE=$(wc -c < "$OUT")
        echo "  AST JSON 大小: $AST_SIZE 字节"
        echo "  结果: 通过"
        PASS=$((PASS + 1))
    else
        echo "  结果: 失败（自举解析器暂不支持该组件的某些语法）"
        FAIL=$((FAIL + 1))
    fi
    echo ""
done

echo "自举编译器前端解析结果: $PASS 个组件通过, $FAIL 个组件失败"
echo "（要求至少 3 个组件通过）"
echo ""

# ============================================================
# 步骤 3：端到端 —— 用主入口运行一个示例程序
# ============================================================
echo ">>> 步骤 3：端到端测试（主入口读取文件并运行）"
echo ""

# 创建示例输入程序（使用简化语法）
DEMO="/tmp/demo_program.co"
cat > "$DEMO" << 'EOF'
让 x = 5
让 y = 10
输出(x + y)

函数 平方(n)
    返回 n * n
结束
输出(平方(7))

让 i = 1
让 总和 = 0
当 i <= 3 循环
    总和 = 总和 + i
    i = i + 1
结束
输出(总和)
EOF

echo "示例程序:"
cat "$DEMO"
echo ""

# 拼接主入口
MAIN_MERGE="/tmp/自举解释器_主_$$.co"
cat "$DIR/词法.co" \
    "$DIR/语法.co" \
    "$DIR/求值.co" \
    "$DIR/主.co" > "$MAIN_MERGE"

echo "--- 运行主入口 ---"
COCN_INPUT="$DEMO" COCN_BACKEND=eval \
    node "$PROJECT_ROOT/bin/cocn.js" "$MAIN_MERGE"
echo ""

# 清理
rm -f "$TMP" "$MAIN_MERGE" "$DEMO" /tmp/ast_*.json

echo "============================================"
echo "  编译与验证全部完成"
echo "  自举前端解析通过: $PASS 个组件"
echo "============================================"
